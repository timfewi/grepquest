// Command ranger-export converts an ASCII Motion v2 project into compact,
// deterministic Go source consumed by the GrepQuest TUI.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"strconv"
	"strings"
)

type project struct {
	Version string `json:"version"`
	Canvas  struct {
		Width  int `json:"width"`
		Height int `json:"height"`
	} `json:"canvas"`
	Layers []layer `json:"layers"`
}

type layer struct {
	Visible       bool           `json:"visible"`
	ContentFrames []contentFrame `json:"contentFrames"`
}

type contentFrame struct {
	Data map[string]cell `json:"data"`
}

type cell struct {
	Char    string `json:"char"`
	Color   string `json:"color"`
	BgColor string `json:"bgColor"`
}

type outputCell struct {
	x, y  int
	char  rune
	color string
}

func main() {
	inputPath := flag.String("input", "", "path to an .asciimtn project")
	outputPath := flag.String("output", "", "path to the generated Go file")
	flag.Parse()
	if *inputPath == "" || *outputPath == "" {
		fatalf("both -input and -output are required")
	}

	data, err := os.ReadFile(*inputPath)
	if err != nil {
		fatalf("read project: %v", err)
	}
	var source project
	if err := json.Unmarshal(data, &source); err != nil {
		fatalf("decode project: %v", err)
	}
	if !strings.HasPrefix(source.Version, "2.") {
		fatalf("unsupported ASCII Motion project version %q", source.Version)
	}
	if source.Canvas.Width < 1 || source.Canvas.Height < 1 {
		fatalf("invalid canvas %dx%d", source.Canvas.Width, source.Canvas.Height)
	}

	composite := make(map[string]cell)
	for _, projectLayer := range source.Layers {
		if !projectLayer.Visible || len(projectLayer.ContentFrames) == 0 {
			continue
		}
		for key, sourceCell := range projectLayer.ContentFrames[0].Data {
			composite[key] = sourceCell
		}
	}

	cells := make([]outputCell, 0, len(composite))
	paletteSet := make(map[string]struct{})
	for key, sourceCell := range composite {
		var x, y int
		if _, err := fmt.Sscanf(key, "%d,%d", &x, &y); err != nil {
			fatalf("invalid cell coordinate %q", key)
		}
		if x < 0 || x >= source.Canvas.Width || y < 0 || y >= source.Canvas.Height {
			fatalf("cell %q is outside the canvas", key)
		}
		runes := []rune(sourceCell.Char)
		if len(runes) != 1 {
			fatalf("cell %q contains %d runes, want one", key, len(runes))
		}
		if !validHexColor(sourceCell.Color) {
			fatalf("cell %q has invalid foreground color %q", key, sourceCell.Color)
		}
		if sourceCell.BgColor != "" && sourceCell.BgColor != "transparent" {
			fatalf("cell %q has unsupported background color %q", key, sourceCell.BgColor)
		}
		if runes[0] == ' ' {
			continue
		}
		color := strings.ToUpper(sourceCell.Color)
		paletteSet[color] = struct{}{}
		cells = append(cells, outputCell{x: x, y: y, char: runes[0], color: color})
	}
	if len(cells) == 0 {
		fatalf("project contains no visible cells")
	}
	sort.Slice(cells, func(i, j int) bool {
		if cells[i].y == cells[j].y {
			return cells[i].x < cells[j].x
		}
		return cells[i].y < cells[j].y
	})

	palette := make([]string, 0, len(paletteSet))
	for color := range paletteSet {
		palette = append(palette, color)
	}
	sort.Strings(palette)
	paletteIndex := make(map[string]int, len(palette))
	for index, color := range palette {
		paletteIndex[color] = index
	}

	var generated strings.Builder
	generated.WriteString("// Code generated by tools/ranger-export; DO NOT EDIT.\n")
	generated.WriteString("package rangerart\n\n")
	fmt.Fprintf(&generated, "const sourceWidth = %d\nconst sourceHeight = %d\n\n", source.Canvas.Width, source.Canvas.Height)
	generated.WriteString("var sourcePalette = []string{\n")
	for _, color := range palette {
		fmt.Fprintf(&generated, "\t%q,\n", color)
	}
	generated.WriteString("}\n\nvar sourceCells = []sourceCell{\n")
	for _, output := range cells {
		fmt.Fprintf(&generated, "\t{x: %d, y: %d, char: %s, color: %d},\n", output.x, output.y, strconv.QuoteRune(output.char), paletteIndex[output.color])
	}
	generated.WriteString("}\n")

	formatted, err := format.Source([]byte(generated.String()))
	if err != nil {
		fatalf("format generated source: %v", err)
	}
	if err := os.WriteFile(*outputPath, formatted, 0o644); err != nil {
		fatalf("write generated source: %v", err)
	}
}

func validHexColor(value string) bool {
	if len(value) != 7 || value[0] != '#' {
		return false
	}
	_, err := strconv.ParseUint(value[1:], 16, 24)
	return err == nil
}

func fatalf(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "ranger-export: "+format+"\n", args...)
	os.Exit(1)
}
